-- Development baseline. Edit this schema directly and reset the local DB when its structure changes.

create table employee (
    id bigint generated by default as identity primary key,
    name varchar(30) not null,
    password_hash varchar(100) not null,
    active_from date not null,
    inactive_from date,
    work_group_code varchar(40) not null check (work_group_code in ('RESTAURANT','GENERAL','FACILITY_SUPPORT','THIRD_FLOOR','DEVELOPMENT_SUPPORT')),
    constraint uq_employee_name unique(name)
);

create table holiday (work_date date primary key, name varchar(60) not null
);

create table responsibility_option (title varchar(60) primary key
);

create table leave_request (
    id bigint generated by default as identity primary key,
    employee_id bigint not null,
    work_date date not null,
    attendance varchar(24) not null,
    updated_at timestamp with time zone not null,
    constraint uq_leave_employee_date unique(employee_id, work_date),
    constraint fk_leave_employee foreign key(employee_id) references employee(id)

);

create table sharing_shop_time_preference (
    id bigint generated by default as identity primary key,
    employee_id bigint not null,
    time_preference varchar(16) not null,
    constraint uq_sharing_shop_time_preference_employee unique(employee_id),
    constraint fk_sharing_shop_time_preference_employee foreign key(employee_id) references employee(id)
);

create table work_task (
    id bigint generated by default as identity primary key,
    activity_code varchar(40) not null,
    work_date date not null,
    code varchar(40) not null,
    name varchar(60) not null,
    period varchar(16) not null,
    required_workers integer not null check (required_workers >= 0),
    status varchar(16) not null,
    created_at timestamp with time zone not null,
    assigned_at timestamp with time zone,
    constraint uq_task_activity_date_code unique(work_date, activity_code, code)

);

create table task_assignment (
    id bigint generated by default as identity primary key,
    task_id bigint not null,
    employee_id bigint not null,
    name varchar(30) not null,
    attendance varchar(24) not null,
    constraint uq_task_employee unique(task_id, employee_id),
    constraint fk_assignment_task foreign key(task_id) references work_task(id)

);

create table task_warning (
    task_id bigint not null,
    warning_order integer not null,
    message varchar(255) not null,
    primary key(task_id, warning_order),
    constraint fk_warning_task foreign key(task_id) references work_task(id)

);

create table employee_responsibility (
    employee_id bigint not null,
    duty_order integer not null,
    title varchar(60) not null,
    primary key(employee_id, duty_order),
    constraint fk_responsibility_employee foreign key(employee_id) references employee(id),
    constraint fk_responsibility_option foreign key(title) references responsibility_option(title)
);

create table employee_photo (
    employee_id bigint primary key,
    image blob not null,
    constraint fk_photo_employee foreign key(employee_id) references employee(id)

);

create table activity_registration (
    id bigint generated by default as identity primary key,
    activity_code varchar(40) not null,
    employee_id bigint not null,
    constraint uq_activity_registration unique(activity_code, employee_id),
    constraint fk_registration_employee foreign key(employee_id) references employee(id)
);

create table exclusion_reason (
 id bigint generated by default as identity primary key, activity_code varchar(40) not null, name varchar(60) not null,
 constraint uq_exclusion_reason unique(activity_code,name)

);

create table exclusion_requirement (
 id bigint generated by default as identity primary key, reason_id bigint not null, effective_from date not null, required_workers integer not null,
 constraint uq_exclusion_requirement unique(reason_id,effective_from),
 constraint fk_requirement_reason foreign key(reason_id) references exclusion_reason(id)

);

create table daily_exclusion (
 id bigint generated by default as identity primary key, reason_id bigint not null, activity_code varchar(40) not null, work_date date not null, employee_id bigint not null,
 constraint uq_daily_exclusion unique(activity_code,work_date,employee_id),
 constraint fk_daily_reason foreign key(reason_id) references exclusion_reason(id),
 constraint fk_daily_employee foreign key(employee_id) references employee(id)

);

create table support_exchange_request (
 id bigint generated by default as identity primary key, source_id bigint not null, target_id bigint not null, requester_id bigint not null, recipient_id bigint not null, expires_at timestamp with time zone not null,
 constraint uq_exchange_pair unique(source_id,target_id),
 constraint fk_exchange_source foreign key(source_id) references daily_exclusion(id) on delete cascade,
 constraint fk_exchange_target foreign key(target_id) references daily_exclusion(id) on delete cascade,
 constraint fk_exchange_requester foreign key(requester_id) references employee(id),
 constraint fk_exchange_recipient foreign key(recipient_id) references employee(id)

);

create index ix_task_date on work_task(work_date);

create index ix_daily_reason_date on daily_exclusion(reason_id,work_date);

create index ix_exchange_expiry on support_exchange_request(expires_at);

