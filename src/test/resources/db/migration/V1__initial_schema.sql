CREATE TABLE employee (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    active_from DATE NOT NULL,
    inactive_from DATE NOT NULL,
    excluded_by_admin BOOLEAN NOT NULL,
    work_group VARCHAR(40) NOT NULL,
    CONSTRAINT uq_employee_name UNIQUE (name),
    CONSTRAINT chk_employee_work_group CHECK (work_group IN ('RESTAURANT', 'GENERAL', 'FACILITY_SUPPORT', 'THIRD_FLOOR', 'DEVELOPMENT_SUPPORT'))
);

CREATE TABLE employee_photo (
    employee_id BIGINT PRIMARY KEY,
    image BLOB NOT NULL,
    CONSTRAINT fk_photo_employee FOREIGN KEY (employee_id) REFERENCES employee (id)
);

CREATE TABLE holiday (
    date DATE PRIMARY KEY,
    name VARCHAR(60) NOT NULL
);

CREATE TABLE leave_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    work_date DATE NOT NULL,
    attendance VARCHAR(24) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_leave_employee_date UNIQUE (employee_id, work_date),
    CONSTRAINT fk_leave_employee FOREIGN KEY (employee_id) REFERENCES employee (id)
);

CREATE TABLE activity_registration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_code VARCHAR(40) NOT NULL,
    employee_id BIGINT NOT NULL,
    CONSTRAINT uq_activity_registration UNIQUE (activity_code, employee_id),
    CONSTRAINT fk_registration_employee FOREIGN KEY (employee_id) REFERENCES employee (id)
);

CREATE TABLE work_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_code VARCHAR(40) NOT NULL,
    work_date DATE NOT NULL,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(60) NOT NULL,
    period VARCHAR(16) NOT NULL,
    required_workers INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_task_activity_date_code UNIQUE (work_date, activity_code, code),
    CONSTRAINT chk_task_required_workers CHECK (required_workers >= 0)
);

CREATE INDEX ix_task_date ON work_task (work_date);

CREATE TABLE task_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    name VARCHAR(30) NOT NULL,
    attendance VARCHAR(24) NOT NULL,
    CONSTRAINT uq_task_employee UNIQUE (task_id, employee_id),
    CONSTRAINT fk_assignment_task FOREIGN KEY (task_id) REFERENCES work_task (id)
);

CREATE TABLE task_warning (
    task_id BIGINT NOT NULL,
    warning_order INTEGER NOT NULL,
    message VARCHAR(255) NOT NULL,
    PRIMARY KEY (task_id, warning_order),
    CONSTRAINT fk_warning_task FOREIGN KEY (task_id) REFERENCES work_task (id)
);

CREATE TABLE sharing_shop_time_preference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    time_preference VARCHAR(16) NOT NULL,
    CONSTRAINT uq_sharing_shop_time_preference_employee UNIQUE (employee_id),
    CONSTRAINT fk_sharing_shop_time_preference_employee FOREIGN KEY (employee_id) REFERENCES employee (id)
);

CREATE TABLE cafeteria_support_requirement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_from DATE NOT NULL,
    required_workers INTEGER NOT NULL,
    CONSTRAINT uq_cafeteria_support_requirement UNIQUE (effective_from)
);

CREATE TABLE cafeteria_support_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_date DATE NOT NULL,
    employee_id BIGINT NOT NULL,
    CONSTRAINT uq_cafeteria_support_assignment UNIQUE (work_date, employee_id),
    CONSTRAINT fk_cafeteria_support_employee FOREIGN KEY (employee_id) REFERENCES employee (id)
);

CREATE TABLE cafeteria_support_exchange_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    target_id BIGINT NOT NULL,
    requester_id BIGINT NOT NULL,
    recipient_id BIGINT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_cafeteria_support_exchange UNIQUE (source_id, target_id),
    CONSTRAINT fk_cafeteria_exchange_source FOREIGN KEY (source_id) REFERENCES cafeteria_support_assignment (id) ON DELETE CASCADE,
    CONSTRAINT fk_cafeteria_exchange_target FOREIGN KEY (target_id) REFERENCES cafeteria_support_assignment (id) ON DELETE CASCADE,
    CONSTRAINT fk_cafeteria_exchange_requester FOREIGN KEY (requester_id) REFERENCES employee (id),
    CONSTRAINT fk_cafeteria_exchange_recipient FOREIGN KEY (recipient_id) REFERENCES employee (id)
);

CREATE INDEX ix_cafeteria_exchange_expiry ON cafeteria_support_exchange_request (expires_at);

